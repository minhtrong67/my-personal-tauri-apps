import {formatValue,adjustDecimals,parseTyped,isDateFormat,dateToSerial,generalText} from '../src/js/numfmt.js';
import {tokenize,parseRef,refToString,shiftFormula,rewriteFormula,adjustRefLines,colName,colIndex} from '../src/js/refs.js';
let fail=0; const eq=(a,b,m)=>{ if(a!==b){fail++;console.log('FAIL',m,JSON.stringify(a),'!=',JSON.stringify(b));} };
eq(formatValue(1234.5,'#,##0.00'),'1,234.50','thou');
eq(formatValue(0.256,'0.0%'),'25.6%','pct');
eq(formatValue(1234.567,'"$"#,##0.00'),'$1,234.57','usd');
eq(formatValue(1234567,'#,##0" ₫"'),'1,234,567 ₫','vnd');
eq(formatValue(-5,'0.00'),'-5.00','neg');
eq(formatValue(-5,'0.00;(0.00)'),'(5.00)','negsec');
eq(formatValue(0.5,'0'),'1','round half up');  
eq(formatValue(1234.5,'0.00E+00'),'1.23E+03','sci');
eq(formatValue(45000,'yyyy-mm-dd'),'2023-03-15','date');
eq(formatValue(45000.5,'yyyy-mm-dd hh:mm'),'2023-03-15 12:00','datetime');
eq(formatValue(45000,'dd/mm/yyyy'),'15/03/2023','ddmmyyyy');
eq(formatValue(0.75,'hh:mm:ss'),'18:00:00','time');
eq(formatValue('abc','@'),'abc','text');
eq(formatValue(3.14159265358979,'General'),'3.141592654','gen');
eq(formatValue(1e12,'General'),'1.00000E+12'.replace('.00000','') ,'gen big');
eq(generalText(0.1+0.2),'0.3','float');
eq(adjustDecimals('General',1),'0.0','dec+');
eq(adjustDecimals('0.00',-1),'0.0','dec-');
eq(adjustDecimals('#,##0',1),'#,##0.0','dec thousands');
eq(isDateFormat('yyyy-mm-dd'),true,'isdate'); eq(isDateFormat('0.00'),false,'isdate0');
eq(JSON.stringify(parseTyped('1,234.5','en')),'{"v":1234.5}','parse en');
eq(JSON.stringify(parseTyped('1.234,5','vi')),'{"v":1234.5}','parse vi');
eq(JSON.stringify(parseTyped('12%','en')),'{"v":0.12,"nf":"0%"}','pct');
eq(parseTyped('2023-03-15','en').v,45000,'iso');
eq(parseTyped('15/03/2023','vi').v,45000,'vi date');
eq(parseTyped('hello','en'),null,'text');
eq(dateToSerial(1900,3,1),61,'serial 61');
// refs
eq(colName(0)+colName(25)+colName(26)+colName(702),'AZAAAAA','colName'); eq(colIndex('AA'),26,'colIndex');
eq(tokenize('SUM(A1:B2,LOG10(3))+Sheet1!C3').filter(t=>t.t==='ref').map(t=>t.x).join('|'),'A1:B2|Sheet1!C3','tokens');
eq(shiftFormula('A1+$B$2+C3:D4',1,2),'C2+$B$2+E4:F5','shift');
eq(shiftFormula('A1',-1,0),'#REF!','shift oob');
eq(refToString(parseRef("'My Sheet'!$A$1:B2")),"'My Sheet'!$A$1:B2",'quote');
eq(rewriteFormula('SUM(A1:A5)+B7',r=>adjustRefLines(r,'row',2,1)),'SUM(A1:A6)+B8','insert row');
eq(rewriteFormula('SUM(A1:A5)+B7+C3',r=>adjustRefLines(r,'row',2,-1)),'SUM(A1:A4)+B6+#REF!','delete row');
eq(rewriteFormula('A3',r=>adjustRefLines(r,'row',2,-1)),'#REF!','delete hit');
console.log(fail?('FAILURES '+fail):'numfmt+refs: all passed');
